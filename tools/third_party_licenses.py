"""Write THIRD_PARTY_LICENSES.md for everything that PyInstaller bundles into Glowtray.exe.

Run it in the environment used for the build, after `pip install -r requirements.txt`:

    python tools/third_party_licenses.py

It follows requirements.txt and the dependencies of each package as installed, so the result matches what the exe
actually contains on Windows.
"""
import importlib.metadata as md
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD_PARTY_LICENSES.md")
LICENSE_FILE = re.compile(r"(^|/)(LICEN[CS]E|COPYING)[^/]*$", re.I)

# Packages whose wheels ship no license file; the text comes from their source repositories
FALLBACK = {"proxy-tools": "proxy_tools.txt", "winrt-": "winrt.txt"}
# Fills in missing package metadata, or corrects it where it disagrees with the license in the source repository
LICENSE_NAME = {"proxy-tools": "BSD", "clr-loader": "MIT"}

HEADER = """# Third-party licenses

`Glowtray.exe` bundles the Python runtime and the open-source packages listed below. Glowtray's own code is under the
[MIT License](LICENSE). This file is generated by `tools/third_party_licenses.py`.

**pystray** is licensed under the GNU Lesser General Public License v3. Its full text is included below. Glowtray uses
pystray unmodified, and Glowtray's complete source code is available at https://github.com/Tolgaugur/GlowTray, so you
can rebuild the exe with a different or modified version of pystray by following *Building the exe* in the README.

The exe is built with [PyInstaller](https://pyinstaller.org/), whose bootloader is licensed under the GPL 2.0 with an
exception that places no obligations on the programs it packages.
"""


def norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def requirement_names():
    with open(os.path.join(ROOT, "requirements.txt"), encoding="utf-8") as f:
        return [re.match(r"[A-Za-z0-9_.\-]+", line).group(0) for line in f if line.strip() and line[0].isalnum()]


def collect():
    """Installed distributions reachable from requirements.txt, keyed by normalized name."""
    found = {}

    def walk(name):
        key = norm(name)
        if key in found:
            return
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            return  # not installed, so not needed on this platform
        found[key] = dist
        for req in dist.requires or []:
            if "extra ==" not in req:
                walk(re.match(r"[A-Za-z0-9_.\-]+", req).group(0))

    for name in requirement_names():
        walk(name)
    return found


def license_name(key, dist):
    if key in LICENSE_NAME:
        return LICENSE_NAME[key]
    meta = dist.metadata
    text = meta.get("License-Expression") or meta.get("License") or ""
    if text and "\n" not in text and len(text) < 60:
        return text
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    return classifiers[0] if classifiers else text.splitlines()[0] if text else "see below"


def license_texts(key, dist):
    texts = []
    for f in dist.files or []:
        if LICENSE_FILE.search(str(f).replace("\\", "/")):
            texts.append(f.read_text(encoding="utf-8").strip())
    if not texts:
        for prefix, file in FALLBACK.items():
            if key.startswith(prefix):
                with open(os.path.join(ROOT, "tools", "licenses", file), encoding="utf-8") as fh:
                    texts.append(fh.read().strip())
                break
    if not texts:
        sys.exit(f"No license text found for {dist.metadata['Name']}; add one to tools/licenses/")
    return texts


def homepage(dist):
    meta = dist.metadata
    urls = dict(u.split(",", 1) for u in meta.get_all("Project-URL") or [])
    urls = {k.strip().lower(): v.strip() for k, v in urls.items()}
    for label in ("homepage", "source", "sources", "source code", "repository"):
        if label in urls:
            return urls[label]
    return meta.get("Home-page") or next(iter(urls.values()), "")


def main():
    dists = collect()
    # All winrt-* packages come from one project with one license, so list them together
    winrt = sorted(k for k in dists if k.startswith("winrt-"))
    rows, sections = [], []
    for key in sorted(dists):
        if key in winrt[1:]:
            continue
        dist = dists[key]
        name = "winrt-* (" + ", ".join(dists[k].metadata["Name"] for k in winrt) + ")" if key in winrt else dist.metadata["Name"]
        rows.append(f"| {name} | {dist.version} | {license_name(key, dist)} | {homepage(dist)} |")
        body = "\n\n".join(license_texts(key, dist))
        sections.append(f"## {name} {dist.version}\n\n```text\n{body}\n```\n")

    python_license = os.path.join(sys.base_prefix, "LICENSE.txt")
    py = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"
    rows.insert(0, f"| Python | {py} | PSF-2.0 | https://www.python.org/ |")
    if os.path.isfile(python_license):
        with open(python_license, encoding="utf-8", errors="replace") as f:
            sections.insert(0, f"## Python {py}\n\n```text\n{f.read().strip()}\n```\n")

    table = "| Component | Version | License | Project |\n|---|---|---|---|\n" + "\n".join(rows)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "\n" + table + "\n\n" + "\n".join(sections))
    print(f"Wrote {OUT} ({len(rows)} components)")


if __name__ == "__main__":
    main()
