"""Write THIRD_PARTY_LICENSES.md for everything that PyInstaller bundles into Glowtray.exe.

Run it after building the exe, in the same environment:

    pyinstaller glowtray.spec
    python tools/third_party_licenses.py

It reads PyInstaller's build output to see which files went into the exe and lists the installed packages they came
from. That includes packages nobody asked for directly, such as the parts of setuptools and PyInstaller itself that
end up inside the exe.
"""
import ast
import importlib.metadata as md
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD_PARTY_LICENSES.md")
BUILD = os.path.join(ROOT, "build", "glowtray")  # PyInstaller's work folder for glowtray.spec
LICENSE_FILE = re.compile(r"(^|/)(LICEN[CS]E|COPYING)[^/]*$", re.I)

# Packages whose wheels ship no license file; the text comes from their source repositories
FALLBACK = {"proxy-tools": "proxy_tools.txt", "winrt-": "winrt.txt"}
# Fills in missing package metadata, or corrects it where it disagrees with the license in the source repository
LICENSE_NAME = {
    "proxy-tools": "BSD",
    "clr-loader": "MIT",
    "pyinstaller": "GPL-2.0-or-later with bootloader exception; run-time hooks Apache-2.0",
}

HEADER = """# Third-party licenses

`Glowtray.exe` bundles the Python runtime and the open-source packages listed below. Glowtray's own code is under the
[MIT License](LICENSE). This file is generated by `tools/third_party_licenses.py` from the files that PyInstaller
actually put into the exe.

**pystray** is licensed under the GNU Lesser General Public License v3. Its full text is included below. Glowtray uses
pystray unmodified, and Glowtray's complete source code is available at https://github.com/Tolgaugur/GlowTray, so you
can rebuild the exe with a different or modified version of pystray by following *Building the exe* in the README.

The exe is built with [PyInstaller](https://pyinstaller.org/). Its bootloader and loader modules are covered by the
GPL 2.0 with an exception that places no obligations on the programs it packages, and the run-time hooks it adds are
under the Apache License 2.0; the full terms are included below. PyInstaller also bundles parts of **setuptools**,
including packages that setuptools vendors; their licenses are included in the setuptools section.
"""


def norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def bundled_files():
    """Source paths of the modules, binaries and data files PyInstaller put into the exe."""
    paths = []
    for name, index in (("PYZ-00.toc", 1), ("PKG-00.toc", 2)):
        toc_path = os.path.join(BUILD, name)
        if not os.path.isfile(toc_path):
            sys.exit(f"{toc_path} not found. Build the exe first (pyinstaller glowtray.spec) in this environment.")
        with open(toc_path, encoding="utf-8") as f:
            toc = ast.literal_eval(f.read())
        paths += [e[1] for e in toc[index] if isinstance(e, tuple) and len(e) > 1 and isinstance(e[1], str)]
    return [p for p in paths if os.path.isabs(p)]


def collect():
    """Installed distributions that own a file in the exe, keyed by normalized name."""
    owner = {}
    for dist in md.distributions():
        for f in dist.files or []:
            owner[os.path.normcase(os.path.abspath(f.locate()))] = dist
    python_dir = os.path.normcase(os.path.abspath(sys.base_prefix)) + os.sep  # covered by the Python license
    own_dir = os.path.normcase(ROOT) + os.sep  # Glowtray's code, and PyInstaller's loader compiled into build/
    found, unknown = {}, set()
    for path in bundled_files():
        path = os.path.normcase(os.path.abspath(path))
        dist = owner.get(path)
        if dist is not None:
            found[norm(dist.metadata["Name"])] = dist
        elif not path.startswith((python_dir, own_dir)):
            unknown.add(path)
    if unknown:
        sys.exit("These bundled files belong to no installed package, so their license is unknown:\n  "
                 + "\n  ".join(sorted(unknown)))
    return found


def license_name(key, dist):
    if key in LICENSE_NAME:
        return LICENSE_NAME[key]
    meta = dist.metadata
    text = meta.get("License-Expression") or meta.get("License") or ""
    if text and "\n" not in text and len(text) < 60:
        return text
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    return classifiers[0] if classifiers else text.splitlines()[0] if text else "see below"


def license_text(key, dist):
    texts = []
    for f in dist.files or []:
        path = str(f).replace("\\", "/")
        if LICENSE_FILE.search(path):
            texts.append((path, f.read_text(encoding="utf-8").strip()))
    if not texts:
        for prefix, file in FALLBACK.items():
            if key.startswith(prefix):
                with open(os.path.join(ROOT, "tools", "licenses", file), encoding="utf-8") as fh:
                    texts.append((None, fh.read().strip()))
                break
    if not texts:
        sys.exit(f"No license text found for {dist.metadata['Name']}; add one to tools/licenses/")
    if len(texts) == 1:
        return texts[0][1]
    # Several files (e.g. setuptools and the packages it vendors): say which text is which
    return "\n\n".join(f"==> {path} <==\n\n{text}" for path, text in texts)


def homepage(dist):
    meta = dist.metadata
    urls = dict(u.split(",", 1) for u in meta.get_all("Project-URL") or [])
    urls = {k.strip().lower(): v.strip() for k, v in urls.items()}
    for label in ("homepage", "source", "sources", "source code", "repository"):
        if label in urls:
            return urls[label]
    return meta.get("Home-page") or next(iter(urls.values()), "")


def main():
    dists = collect()
    # All winrt-* packages come from one project with one license, so list them together
    winrt = sorted(k for k in dists if k.startswith("winrt-"))
    rows, sections = [], []
    for key in sorted(dists):
        if key in winrt[1:]:
            continue
        dist = dists[key]
        name = "winrt-* (" + ", ".join(dists[k].metadata["Name"] for k in winrt) + ")" if key in winrt else dist.metadata["Name"]
        rows.append(f"| {name} | {dist.version} | {license_name(key, dist)} | {homepage(dist)} |")
        body = license_text(key, dist)
        sections.append(f"## {name} {dist.version}\n\n```text\n{body}\n```\n")

    python_license = os.path.join(sys.base_prefix, "LICENSE.txt")
    py = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"
    rows.insert(0, f"| Python | {py} | PSF-2.0 | https://www.python.org/ |")
    if os.path.isfile(python_license):
        with open(python_license, encoding="utf-8", errors="replace") as f:
            sections.insert(0, f"## Python {py}\n\n```text\n{f.read().strip()}\n```\n")

    table = "| Component | Version | License | Project |\n|---|---|---|---|\n" + "\n".join(rows)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "\n" + table + "\n\n" + "\n".join(sections))
    print(f"Wrote {OUT} ({len(rows)} components)")


if __name__ == "__main__":
    main()
